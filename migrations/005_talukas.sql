-- Creates talukas table and seeds all talukas for 36 Maharashtra districts.
-- Marathi names (name_mr) use English values as placeholders — update via admin.

CREATE TABLE talukas (
  id            SERIAL       PRIMARY KEY,
  district_id   SMALLINT     NOT NULL REFERENCES districts(id),
  district_name VARCHAR(100),
  name_en       VARCHAR(100) NOT NULL,
  name_mr       VARCHAR(100) NOT NULL,
  sort_order    SMALLINT     NOT NULL DEFAULT 0,
  is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  deleted_at    TIMESTAMPTZ,
  UNIQUE (name_en, district_id)
);

CREATE INDEX talukas_district_idx ON talukas (district_id) WHERE deleted_at IS NULL;

CREATE TRIGGER talukas_updated_at BEFORE UPDATE ON talukas
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

